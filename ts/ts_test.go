// files checks the Kogo sources, one file each, against the real
// prelude, and gives the TypeScript of their api lists.
func files(t *testing.T, sources ...string) map[string][]byte {
	t.Helper()
	pre, err := prelude.Files()
	if err != nil {
		t.Fatal(err)
	}
	var program []*syntax.File
	for i, src := range sources {
		f, err := syntax.Parse(fmt.Sprintf("f%d.kg", i), []byte(src))
		if err != nil {
			t.Fatal(err)
		}
		program = append(program, f)
	}
	info, errs := check.Check(pre, program, nil)
	if errs != nil {
		t.Fatal(errs)
	}
	return Files(info)
}

// head is a program's head: its imports, an environment and an
// operation with no input and no answer.
const head = `package a
import kogo.rpc.Request
data class Env(val n: Int)
fun ping(tx: Tx, env: Env, request: Request, input: Unit): Either<String, Unit> = either { }
`

// Each row of spec.md 15.4's table, an enum with no constants, a type
// that holds itself, and the types in the order of their names, not
// the order reached.
func TestFile(t *testing.T) {
	got := files(t, strings.Replace(head, "\n", "\nimport kogo.time.LocalDate\nimport kogo.time.LocalTime\n", 1)+`api ops unchecked { ping ungated, tree ungated, job ungated }
fun job(db: Db, env: Env, request: Request, input: Ask): Either<String, Job?> = either { raise("no") }
fun tree(tx: Tx, env: Env, request: Request, input: Unit): Either<String, List<Tree>> = either { raise("no") }
data class Ask(val id: Uuid, val n: Int, val big: Long, val x: Double, val ok: Boolean, val day: LocalDate, val at: LocalTime?)
data class Job(val state: State, val none: None, val notes: String?, val tags: List<String?>, val also: List<Int>?)
enum class State { Offered, Confirmed }
enum class None { }
data class Tree(val label: String, val kids: List<Tree>, val up: Tree?)
`)
	want := `// Generated by kogo ts from api ops. Do not edit.

export type Outcome<T> = {type: "ok"; value: T} | {type: "refused"; message: string}

export type Ask = {
  id: string
  n: number
  big: number
  x: number
  ok: boolean
  day: string
  at: string | null
}
export type Job = {
  state: State
  none: None
  notes: string | null
  tags: (string | null)[]
  also: number[] | null
}
export type None = never
export type State = "Offered" | "Confirmed"
export type Tree = {
  label: string
  kids: Tree[]
  up: Tree | null
}

export interface Ops {
  ping: {input: {[k: string]: never}; value: {[k: string]: never}}
  tree: {input: {[k: string]: never}; value: Tree[]}
  job: {input: Ask; value: Job | null}
}
`
	if len(got) != 1 || string(got["ops.ts"]) != want {
		t.Errorf("got %d files, ops.ts:\n%s\nwant:\n%s", len(got), got["ops.ts"], want)
	}
}

// Two lists, in two packages, write a file each, with only the types
// each reaches.
func TestTwoLists(t *testing.T) {
	got := files(t, head+"api ops unchecked { ping ungated, f ungated }\n"+
		"fun f(tx: Tx, env: Env, request: Request, input: Unit): Either<String, State> = either { State.On }\nenum class State { On }",
		"package b\nimport a.ping\napi admin unchecked { ping ungated }")
	want := map[string]string{
		"ops.ts": "export type State = \"On\"\n\nexport interface Ops {\n" +
			"  ping: {input: {[k: string]: never}; value: {[k: string]: never}}\n  f: {input: {[k: string]: never}; value: State}\n}\n",
		"admin.ts": "export interface Admin {\n  ping: {input: {[k: string]: never}; value: {[k: string]: never}}\n}\n",
	}
	if len(got) != len(want) {
		t.Errorf("got %d files, want %d", len(got), len(want))
	}
	const top = "// Generated by kogo ts from api %s. Do not edit.\n\n" +
		`export type Outcome<T> = {type: "ok"; value: T} | {type: "refused"; message: string}` + "\n\n"
	for name, text := range want {
		list := name[:len(name)-3]
		if w := fmt.Sprintf(top, list) + text; string(got[name]) != w {
			t.Errorf("%s:\n%s\nwant:\n%s", name, got[name], w)
		}
	}
}
