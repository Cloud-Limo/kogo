// Package emit writes Go from a checked Kogo program: doc/design.md,
// "The emitter". It writes pure code, spec.md sections 2 to 6,
// expected failures, section 9, SQL and transactions, sections 7
// and 10, the table of each api list, section 15, and each tests
// list, section 16.
//
// Nobody reads the Go. Each line of it begins with a /*line*/
// directive, so that a Go panic's trace names the Kogo file and line,
// padded so that the code starts at one column, and is indented a tab
// for each block or closure it is in; except the later lines of a
// statement's raw string, which hold no code.
package emit

import (
	"cmp"
	"fmt"
	"go/token"
	"maps"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/Cloud-Limo/kogo/check"
	"github.com/Cloud-Limo/kogo/syntax"
)

// The Go packages that emitted code imports: rt, and the prelude's,
// one for each Kogo package of it.
const (
	rtPath      = "github.com/Cloud-Limo/kogo/rt"
	preludePath = "github.com/Cloud-Limo/kogo/prelude/"
)

// Emit gives the Go for a checked program: one file for each Kogo
// package, a.b's at a/b/kogo.go under the directory whose import path
// is root and whose path is out: the line directives name each source
// relative to the directory of the file. It gives errors and no files
// when the program holds what is not emitted yet, or two declarations
// that Go cannot tell apart.
func Emit(info *check.Info, prelude, program []*syntax.File, root, out string) (map[string][]byte, []*syntax.Error) {
	_, files, errs := emitAll(info, prelude, program, root, out)
	return files, errs
}

func emitAll(info *check.Info, prelude, program []*syntax.File, root, outDir string) (*emitter, map[string][]byte, []*syntax.Error) {
	e := &emitter{
		info: info, root: root, names: map[any]string{}, bound: map[string]bool{}, chained: map[*check.TypeDecl]bool{},
		nullable: map[*check.TypeParam]bool{}, scanned: map[*check.Func]bool{},
	}
	bindings := append([]*syntax.File{info.Core}, prelude...)
	for _, f := range bindings {
		e.bound[f.Package.Name] = true
	}
	for _, d := range info.Core.Decls {
		if c, ok := d.(*syntax.ClassDecl); ok && c.Name == "Either" {
			e.either = info.Classes[c]
		}
	}
	e.chains()
	e.name(bindings)
	e.name(program)
	var pkgs []string
	files := map[string][]*syntax.File{}
	for _, f := range program {
		pkg := f.Package.Name
		if e.file = f; e.bound[pkg] {
			e.refuse(f.Package, "go-name", "package %s is the prelude's: name this file's package something else", pkg)
		}
		if files[pkg] == nil {
			pkgs = append(pkgs, pkg)
		}
		files[pkg] = append(files[pkg], f)
	}
	out := map[string][]byte{}
	outDir, _ = filepath.Abs(outDir)
	for _, pkg := range pkgs {
		dir := strings.ReplaceAll(pkg, ".", "/")
		e.pkg, e.imports, e.width = pkg, map[string]string{}, 0
		paths := map[*syntax.File]string{}
		for _, f := range files[pkg] {
			abs, _ := filepath.Abs(f.Name)
			rel, _ := filepath.Rel(filepath.Join(outDir, dir), abs)
			paths[f] = filepath.ToSlash(rel)
			e.width = max(e.width, len(fmt.Sprintf("/*line %s:%d*/ ", paths[f], f.Lines)))
		}
		body := e.capture(func() {
			for _, f := range files[pkg] {
				e.file, e.path = f, paths[f]
				for _, d := range f.Decls {
					e.decl(d)
				}
				for _, d := range f.APIs {
					e.table(d)
				}
				for _, d := range f.Tests {
					e.tests(d)
				}
			}
		})
		name := pkg[strings.LastIndexByte(pkg, '.')+1:]
		if token.IsKeyword(name) || name == "main" {
			name += "_kg"
		}
		var head strings.Builder
		fmt.Fprintf(&head, "// Code generated by kogo emit from package %s. DO NOT EDIT.\n\npackage %s\n\n", pkg, name)
		for _, path := range slices.Sorted(maps.Keys(e.imports)) {
			fmt.Fprintf(&head, "import %s %q\n", e.imports[path], path)
		}
		out[dir+"/kogo.go"] = []byte(head.String() + "\n" + body)
	}
	// A T? whose T is itself nullable would be two pointers in Go. A
	// T given to a fun that uses its own as T? is used so.
	for changed := true; changed; {
		changed = false
		for _, f := range e.flows {
			if e.nullable[f[1]] && !e.nullable[f[0]] {
				e.nullable[f[0]], changed = true, true
			}
		}
	}
	for _, i := range e.insts {
		if e.nullable[i.param] {
			e.file = i.file
			e.refuse(i.at, "not-yet-emitted", "a nullable type argument for %s, which is used as %s? in %s or a fun it calls, is not emitted yet: pass %s a type that is not nullable, and keep the null outside, as mapNotNull { it } or ?: does", i.param.Name, i.param.Name, i.name, i.name)
		}
	}
	if len(e.errs) > 0 {
		order := map[string]int{}
		for i, f := range program {
			order[f.Name] = i
		}
		slices.SortStableFunc(e.errs, func(a, b *syntax.Error) int {
			return cmp.Or(cmp.Compare(order[a.File], order[b.File]), cmp.Compare(a.Line, b.Line), cmp.Compare(a.Column, b.Column))
		})
		e.errs = slices.CompactFunc(e.errs, func(a, b *syntax.Error) bool { return *a == *b })
		return e, nil, e.errs
	}
	return e, out, nil
}

type emitter struct {
	info     *check.Info
	root     string // the import path of the directory written to
	errs     []*syntax.Error
	names    map[any]string            // the Go name of each top-level type, fun, val, enum constant, enum's entries and api table
	bound    map[string]bool           // the Kogo packages that Go implements: the prelude's
	chained  map[*check.TypeDecl]bool  // the data classes that get a chain: see chains
	nullable map[*check.TypeParam]bool // the type parameters used as T?
	flows    [][2]*check.TypeParam     // a type parameter, and one it is given as a type argument for
	scanned  map[*check.Func]bool      // the funs whose signatures are read for that
	either   *check.TypeDecl           // the core's Either
	insts    []inst

	pkg     string            // the Kogo package being written
	imports map[string]string // the alias of each Go package it imports
	file    *syntax.File
	path    string      // the file, as a line directive names it
	width   int         // the width of the directives and their padding
	line    int         // the source line of the statement at hand
	depth   int         // the blocks and closures the Go at hand is in
	at      syntax.Node // the statement at hand
	out     *strings.Builder
	last    string // the line of Go written last
	fn      *scope

	// The Kogo fun being written.
	this   check.Type // the type of this, or nil
	result check.Type
	loops  []*loop
	raise  *raise // the raise scope written in, or nil
}

// A raise is a raise scope as the Go inside it sees it: its handle,
// the first parameter of its block, and the type Raise<E>.
type raise struct {
	handle string
	typ    *check.Named
}

// An inst is a nullable type argument, and the type parameter it
// stands for.
type inst struct {
	param *check.TypeParam
	name  string // the fun or type that declares it
	file  *syntax.File
	at    syntax.Node
}

// A scope is one top-level declaration's Go names: of each local,
// parameter, local fun and type parameter.
type scope struct {
	names map[any]string
	used  map[string]bool
	temps int
}

type loop struct {
	label string
	used  bool
}

func (e *emitter) refuse(at syntax.Node, code, format string, args ...any) {
	p := first(at)
	e.errs = append(e.errs, &syntax.Error{File: e.file.Name, Line: p.Line, Column: p.Column, Code: code, Message: fmt.Sprintf(format, args...)})
}

// notYet refuses what a later slice of the emitter will write.
func (e *emitter) notYet(at syntax.Node, what, fix string) {
	e.refuse(at, "not-yet-emitted", "%s is not emitted yet: %s", what, fix)
}

// first gives where a node's text begins: an operator and a call are
// positioned further in.
func first(n syntax.Node) syntax.Pos {
	switch x := n.(type) {
	case *syntax.Call:
		return first(x.Fun)
	case *syntax.Select:
		return first(x.X)
	case *syntax.Binary:
		return first(x.X)
	case *syntax.Index:
		return first(x.X)
	case *syntax.Is:
		return first(x.X)
	}
	return n.At()
}

// dir is what every line of Go begins with: its line directive,
// padded to the file's width, and a tab for each level it is in.
func (e *emitter) dir() string {
	tabs := strings.Repeat("\t", e.depth)
	if e.line == 0 {
		return tabs
	}
	d := fmt.Sprintf("/*line %s:%d*/", e.path, e.line)
	return d + strings.Repeat(" ", max(e.width-len(d), 1)) + tabs
}

// w writes one line of Go.
func (e *emitter) w(format string, args ...any) {
	e.last = fmt.Sprintf(format, args...)
	e.out.WriteString(e.dir() + e.last + "\n")
}

// open writes a line that opens a block, and shut one that closes it.
// turn writes one that does both, as } else { and a case.
func (e *emitter) open(format string, args ...any) {
	e.w(format, args...)
	e.depth++
}

func (e *emitter) shut(format string, args ...any) {
	e.depth--
	e.w(format, args...)
}

func (e *emitter) turn(format string, args ...any) {
	e.shut(format, args...)
	e.depth++
}

// inner gives the Go that work writes a level in: a closure's body.
func (e *emitter) inner(work func()) string {
	e.depth++
	defer func() { e.depth-- }()
	return e.capture(work)
}

// capture gives the Go that work writes.
func (e *emitter) capture(work func()) string {
	defer func(out *strings.Builder) { e.out = out }(e.out)
	e.out = &strings.Builder{}
	work()
	return e.out.String()
}

// enter begins the statement or declaration n: its line is the one
// that the Go written for it is traced to. It gives the way back.
func (e *emitter) enter(n syntax.Node) func() {
	line, at := e.line, e.at
	e.line, e.at = first(n).Line, n
	return func() { e.line, e.at = line, at }
}

// use gives the alias under which the file imports a Go package.
func (e *emitter) use(path string) string {
	if e.imports[path] == "" {
		e.imports[path] = "p" + strconv.Itoa(len(e.imports)+1)
	}
	return e.imports[path]
}

func (e *emitter) rt() string { return e.use(rtPath) }

// qualify gives a top-level Go name as the package being written
// names it.
func (e *emitter) qualify(pkg, name string) string {
	dir := strings.ReplaceAll(pkg, ".", "/")
	switch {
	case pkg == e.pkg:
		return name
	case e.bound[pkg]:
		return e.use(preludePath+dir) + "." + name
	}
	return e.use(e.root+"/"+dir) + "." + name
}

// local gives a Go name to a local, a parameter, a local fun or a
// type parameter: its own with _ after it, which no top-level name,
// keyword, temporary or import has, and numbered when the declaration
// already has one of that name.
func (e *emitter) local(obj any, name string) string {
	g := name + "_"
	for i := 2; e.fn.used[g]; i++ {
		g = fmt.Sprintf("%s_%d_", name, i)
	}
	e.fn.used[g], e.fn.names[obj] = true, g
	return g
}

func (e *emitter) temp() string {
	e.fn.temps++
	return "t" + strconv.Itoa(e.fn.temps)
}
