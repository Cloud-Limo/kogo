package sqlpass

import (
	"bytes"
	"fmt"
	"go/format"
	"regexp"
	"strings"
)

// A Func is a checked statement and the name of the Go function to
// emit for it. Exists asks whether the statement gives any row.
type Func struct {
	Name   string
	Stmt   *Statement
	Exists bool
}

// The Go type of each Kogo type, as pgx reads and writes it. The
// pgtype ones stand in until the prelude has its own.
var goTypes = map[string]string{
	"Boolean": "bool", "Int": "int32", "Long": "int64", "Double": "float64", "Decimal": "pgtype.Numeric",
	"String": "string", "Uuid": "[16]byte", "Instant": "time.Time", "LocalDate": "pgtype.Date",
	"LocalTime": "pgtype.Time", "Duration": "pgtype.Interval",
}

// goType gives the Go type of a value: a slice for a list, a pointer
// for a T?, and a string for an enum until the checker has enums.
func goType(t Type, nullable bool) string {
	g := goTypes[t.Name]
	if t.Enum {
		g = "string"
	}
	switch {
	case t.List:
		return "[]" + g
	case nullable:
		return "*" + g
	}
	return g
}

var goName = regexp.MustCompile(`^[A-Z][A-Za-z0-9]*$`)

// Emit writes a Go file with one function per statement. An Exists
// gives whether there is a row; otherwise a statement with columns
// gives a slice of its row struct, and one without gives the count of
// rows affected. Every parameter may be nil, which sends NULL.
func Emit(pkg string, funcs []Func) ([]byte, error) {
	var body bytes.Buffer
	types := "" // every Go type used, to know what to import
	use := func(t Type, nullable bool) string {
		g := goType(t, nullable)
		types += g + " "
		return g
	}
	for _, f := range funcs {
		args, call := "", ""
		for i, p := range f.Stmt.Params {
			args += fmt.Sprintf(", p%d %s", i+1, use(p.Type, true))
			call += fmt.Sprintf(", p%d", i+1)
		}
		if f.Exists {
			fmt.Fprintf(&body, `
func %s(ctx context.Context, tx pgx.Tx%s) (bool, error) {
	rows, err := tx.Query(ctx, %q%s)
	if err != nil {
		return false, err
	}
	found := rows.Next()
	rows.Close()
	return found, rows.Err()
}
`, f.Name, args, f.Stmt.SQL, call)
			continue
		}
		if len(f.Stmt.Columns) == 0 {
			fmt.Fprintf(&body, `
func %s(ctx context.Context, tx pgx.Tx%s) (int64, error) {
	tag, err := tx.Exec(ctx, %q%s)
	return tag.RowsAffected(), err
}
`, f.Name, args, f.Stmt.SQL, call)
			continue
		}
		fmt.Fprintf(&body, "\ntype %sRow struct {\n", f.Name)
		used := map[string]bool{}
		for i, c := range f.Stmt.Columns {
			field := pascal(c.Name)
			if !goName.MatchString(field) || used[field] {
				field = fmt.Sprintf("Column%d", i+1)
			}
			for used[field] { // a column may be named column2
				field += "_"
			}
			used[field] = true
			fmt.Fprintf(&body, "\t%s %s\n", field, use(c.Type, c.Nullable))
		}
		fmt.Fprintf(&body, `}

func %[1]s(ctx context.Context, tx pgx.Tx%[2]s) ([]%[1]sRow, error) {
	rows, err := tx.Query(ctx, %[3]q%[4]s)
	if err != nil {
		return nil, err
	}
	return pgx.CollectRows(rows, pgx.RowToStructByPos[%[1]sRow])
}
`, f.Name, args, f.Stmt.SQL, call)
	}
	src := "// Code generated by kogo-sql. DO NOT EDIT.\n\npackage " + pkg + "\n"
	if len(funcs) > 0 {
		src += "\nimport (\n\t\"context\"\n"
		if strings.Contains(types, "time.") {
			src += "\t\"time\"\n"
		}
		src += "\n\t\"github.com/jackc/pgx/v5\"\n"
		if strings.Contains(types, "pgtype.") {
			src += "\t\"github.com/jackc/pgx/v5/pgtype\"\n"
		}
		src += ")\n"
	}
	return format.Source([]byte(src + body.String()))
}
