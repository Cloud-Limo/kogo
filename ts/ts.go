// Package ts writes the TypeScript of a checked program's api lists
// (spec.md 15.6): for each list, the wire types its operations reach,
// the answer's type and an interface naming each operation's input
// and value.
package ts

import (
	"cmp"
	"fmt"
	"slices"
	"strings"

	"github.com/Cloud-Limo/kogo/check"
)

// Files gives the TypeScript of each api list of a checked program,
// ops's at ops.ts.
func Files(info *check.Info) map[string][]byte {
	files := map[string][]byte{}
	for d, a := range info.APIs {
		files[d.Name+".ts"] = File(d.Name, a)
	}
	return files
}

// File gives the TypeScript of the api list called list. Its types
// stand in the order of their names, so that one program always
// writes the same bytes.
func File(list string, a *check.API) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by kogo ts from api %s. Do not edit.\n\n", list)
	b.WriteString(`export type Outcome<T> = {type: "ok"; value: T} | {type: "refused"; message: string}` + "\n")
	types := slices.SortedFunc(slices.Values(a.Types), func(x, y *check.TypeDecl) int { return strings.Compare(x.Simple(), y.Simple()) })
	if len(types) > 0 {
		b.WriteString("\n")
	}
	for _, d := range types {
		if d.Kind == "enum class" {
			var names []string
			for _, e := range d.Entries {
				names = append(names, `"`+e.Name+`"`)
			}
			fmt.Fprintf(&b, "export type %s = %s\n", d.Simple(), cmp.Or(strings.Join(names, " | "), "never"))
			continue
		}
		fmt.Fprintf(&b, "export type %s = {\n", d.Simple())
		for _, p := range d.Ctor.Params {
			fmt.Fprintf(&b, "  %s: %s\n", p.Name, typ(p.Type))
		}
		b.WriteString("}\n")
	}
	fmt.Fprintf(&b, "\nexport interface %s {\n", check.Interface(list))
	for _, op := range a.Ops {
		fmt.Fprintf(&b, "  %s: {input: %s; value: %s}\n", op.Func.Name, typ(op.Input), typ(op.Answer))
	}
	b.WriteString("}\n")
	return []byte(b.String())
}

// scalars gives the TypeScript of the prelude's types that cross the
// wire (spec.md 15.4), kogo.time's two among them, but List. Unit's
// names no built-in, which a type of the program's could shadow.
var scalars = map[string]string{
	"Boolean": "boolean", "Int": "number", "Long": "number", "Double": "number",
	"String": "string", "Uuid": "string", "Unit": "{[k: string]: never}",
	"LocalDate": "string", "LocalTime": "string",
}

// typ gives the TypeScript of t, a type the checker let onto the wire.
func typ(t check.Type) string {
	if n, ok := t.(*check.Nullable); ok {
		return typ(n.Elem) + " | null"
	}
	n := t.(*check.Named)
	switch d := n.Decl; {
	case d.Pkg != "kogo" && d.Pkg != "kogo.time":
		return d.Simple()
	case d.Name == "List":
		s := typ(n.Args[0])
		if _, ok := n.Args[0].(*check.Nullable); ok {
			s = "(" + s + ")"
		}
		return s + "[]"
	default:
		s, ok := scalars[d.Name]
		if !ok {
			panic("ts: the checker let " + d.Name + " onto the wire, and scalars has no TypeScript for it")
		}
		return s
	}
}
